@doctor_router.post("/patients/{patient_id}/visits")
def check_in(patient_id: int, body: VisitIn, db: Session = Depends(get_db), doctor: Doctor = Depends(get_current_active_doctor)):
    """Check the patient in. One open visit per patient and doctor at a time."""
    _owned_patient(db, doctor, patient_id)
    if db.query(CareVisit).filter(CareVisit.user_id == patient_id, CareVisit.doctor_pk == doctor.id, CareVisit.checked_out_at.is_(None)).first():
        raise HTTPException(409, "This patient is already checked in")
    v = CareVisit(user_id=patient_id, doctor_pk=doctor.id, kind=body.kind, reason=body.reason, facility=body.facility or doctor.hospital, checked_in_at=_now())
    db.add(v); db.commit(); db.refresh(v)
    _tell(db, doctor, patient_id, "Checked in", f"You were checked in at {v.facility or 'the clinic'}.")
    return _visit(v, doctor.full_name)


@doctor_router.post("/patients/{patient_id}/visits/{visit_id}/check-out")
def check_out(patient_id: int, visit_id: int, body: CheckOutIn, db: Session = Depends(get_db), doctor: Doctor = Depends(get_current_active_doctor)):
    _owned_patient(db, doctor, patient_id)
    v = db.query(CareVisit).filter(CareVisit.id == visit_id, CareVisit.user_id == patient_id, CareVisit.doctor_pk == doctor.id).first()
    if not v:
        raise HTTPException(404, "Visit not found")
    if v.checked_out_at is not None:
        raise HTTPException(409, "This visit is already closed")
    v.checked_out_at, v.summary = _now(), body.summary
    db.commit(); db.refresh(v)
    _tell(db, doctor, patient_id, "Checked out", "Your visit summary is in your health record." if v.summary else "Your visit was closed.")
    return _visit(v, doctor.full_name)



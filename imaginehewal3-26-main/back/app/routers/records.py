"""The health record, for the patient (/records) and for their doctor (/doctor-portal/patients/{id}/records).

Patient: reads everything, and writes allergies, immunisations, insurance and dependents.
Doctor (only for patients who linked them): writes laboratory results, radiology reports, visits (check-in and check-out), and may add
allergies and immunisations. Every change reaches the other side live (`records.update` / `care.refresh`). A doctor-written row is
labelled as such; nothing is generated by the system.
"""
from datetime import date, datetime, timezone
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, Field, field_validator
from sqlalchemy.orm import Session

from app.auth.security import get_current_active_doctor, get_current_active_user

patient_router = APIRouter(prefix="/records", tags=["records"])
doctor_router = APIRouter(prefix="/doctor-portal", tags=["doctor_records"])

SEVERITY = ("mild", "moderate", "severe")
FLAGS = ("normal", "low", "high", "critical")
MODALITIES = ("xray", "ct", "mri", "ultrasound", "mammogram", "other")
KINDS = ("clinic", "emergency", "admission")
RELATIONS = ("child", "parent", "spouse", "other")


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _one_of(allowed):
    def check(v):
        if v is not None and v not in allowed:
            raise ValueError("must be one of: " + ", ".join(allowed))
        return v
    return check


def _day(d: Optional[date]) -> Optional[str]:
    return d.isoformat() if d else None


# ------------------------------------------------------------------ shapes
def _allergy(a: PatientAllergy) -> dict:
    return {"id": a.id, "substance": a.substance, "reaction": a.reaction, "severity": a.severity, "source": a.source, "at": _iso(a.created_at)}


def _lab(r: LabResult) -> dict:
    return {"id": r.id, "test": r.test, "value": r.value, "unit": r.unit, "ref_range": r.ref_range, "flag": r.flag, "taken_at": _iso(r.taken_at), "note": r.note}


def _rad(r: RadiologyReport) -> dict:
    return {"id": r.id, "modality": r.modality, "body_part": r.body_part, "facility": r.facility, "performed_at": _iso(r.performed_at),
            "findings": r.findings, "impression": r.impression, "image_url": r.image_url}


def _imm(i: Immunisation) -> dict:
    return {"id": i.id, "vaccine": i.vaccine, "dose": i.dose, "given_on": _day(i.given_on), "facility": i.facility, "source": i.source}


def _ins(p: Optional[InsurancePolicy]) -> Optional[dict]:
    if not p:
        return None
    expired = bool(p.valid_until and p.valid_until < _now().date())
    return {"provider": p.provider, "plan": p.plan, "member_no": p.member_no, "valid_until": _day(p.valid_until), "expired": expired, "coverage_notes": p.coverage_notes}


def _dep(d: Dependent) -> dict:
    return {"id": d.id, "name": d.name, "relationship": d.relationship, "birth_date": _day(d.birth_date), "sex": d.sex,
            "allergies": d.allergies, "conditions": d.conditions, "notes": d.notes}


def _visit(v: CareVisit, doctor: Optional[str] = None) -> dict:
    return {"id": v.id, "facility": v.facility, "kind": v.kind, "reason": v.reason, "doctor": doctor, "checked_in_at": _iso(v.checked_in_at),
            "checked_out_at": _iso(v.checked_out_at), "open": v.checked_out_at is None, "summary": v.summary}


def _record(db: Session, uid: int) -> dict:
    """Everything the record holds for one person, newest first."""
    docs = {d.id: d.full_name for d in db.query(Doctor).all()}
    visits = db.query(CareVisit).filter(CareVisit.user_id == uid).order_by(CareVisit.checked_in_at.desc()).limit(50).all()
    return {
        "allergies": [_allergy(a) for a in db.query(PatientAllergy).filter(PatientAllergy.user_id == uid).order_by(PatientAllergy.id.desc()).all()],
        "labs": [_lab(r) for r in db.query(LabResult).filter(LabResult.user_id == uid).order_by(LabResult.taken_at.desc()).limit(100).all()],
        "radiology": [_rad(r) for r in db.query(RadiologyReport).filter(RadiologyReport.user_id == uid).order_by(RadiologyReport.performed_at.desc()).limit(50).all()],
        "immunisations": [_imm(i) for i in db.query(Immunisation).filter(Immunisation.user_id == uid).order_by(Immunisation.given_on.desc()).all()],
        "insurance": _ins(db.query(InsurancePolicy).filter(InsurancePolicy.user_id == uid).first()),
        "visits": [_visit(v, docs.get(v.doctor_pk)) for v in visits],
        "open_visit": next((_visit(v, docs.get(v.doctor_pk)) for v in visits if v.checked_out_at is None), None),
    }


def _tell(db: Session, doctor: Doctor, patient_id: int, title: str, text: str) -> None:
    db.add(Notification(user_id=patient_id, notification_type="doctor", title=title, message=text, sender_id=doctor.id, sender_type="doctor"))
    db.commit()
    hub.send_from_thread(patient_id, {"type": "records.update"})
    push.notify_users([patient_id], title, text, {"type": "records"})


def _tell_doctor(db: Session, patient_id: int, reason: str) -> None:
    care_chat.refresh_doctor(db, patient_id, reason)


def _https(v: Optional[str]) -> Optional[str]:
    if v and not v.lower().startswith("https://"):
        raise ValueError("the image address must start with https://")
    return v


# ------------------------------------------------------------------ patient
class AllergyIn(BaseModel):
    substance: str = Field(..., min_length=1, max_length=120)
    reaction: Optional[str] = Field(None, max_length=200)
    severity: str = "mild"

    @field_validator("severity")
    @classmethod
    def _sev(cls, v):
        return _one_of(SEVERITY)(v)


class ImmunisationIn(BaseModel):
    vaccine: str = Field(..., min_length=1, max_length=120)
    dose: Optional[str] = Field(None, max_length=30)
    given_on: date
    facility: Optional[str] = Field(None, max_length=120)

    @field_validator("given_on")
    @classmethod
    def _not_future(cls, v):
        if v > _now().date():
            raise ValueError("the date cannot be in the future")
        return v


class InsuranceIn(BaseModel):
    provider: str = Field(..., min_length=1, max_length=120)
    plan: Optional[str] = Field(None, max_length=120)
    member_no: Optional[str] = Field(None, max_length=60)
    valid_until: Optional[date] = None
    coverage_notes: Optional[str] = Field(None, max_length=400)


class DependentIn(BaseModel):
    name: str = Field(..., min_length=1, max_length=120)
    relationship: str = "child"
    birth_date: Optional[date] = None
    sex: Optional[str] = Field(None, max_length=10)
    allergies: Optional[str] = Field(None, max_length=300)
    conditions: Optional[str] = Field(None, max_length=300)
    notes: Optional[str] = Field(None, max_length=400)

    @field_validator("relationship")
    @classmethod
    def _rel(cls, v):
        return _one_of(RELATIONS)(v)



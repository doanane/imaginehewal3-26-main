class EntryIn(BaseModel):
    kind: str
    title: str = Field(..., min_length=1, max_length=120)
    detail: Optional[str] = Field(None, max_length=400)
    on_date: date

    @field_validator("kind")
    @classmethod
    def _kind(cls, v):
        return _one_of(("vaccine", "result", "visit"))(v)


def _entry(e) -> dict:
    return {"id": e.id, "kind": e.kind, "title": e.title, "detail": e.detail, "on_date": _day(e.on_date)}



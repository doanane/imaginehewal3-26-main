class LabIn(BaseModel):
    test: str = Field(..., min_length=1, max_length=120)
    value: str = Field(..., min_length=1, max_length=60)
    unit: Optional[str] = Field(None, max_length=30)
    ref_range: Optional[str] = Field(None, max_length=60)
    flag: str = "normal"
    taken_at: Optional[datetime] = None
    note: Optional[str] = Field(None, max_length=300)

    @field_validator("flag")
    @classmethod
    def _flag(cls, v):
        return _one_of(FLAGS)(v)


class RadiologyIn(BaseModel):
    modality: str
    body_part: str = Field(..., min_length=1, max_length=80)
    facility: Optional[str] = Field(None, max_length=120)
    performed_at: Optional[datetime] = None
    findings: Optional[str] = Field(None, max_length=4000)
    impression: Optional[str] = Field(None, max_length=2000)
    image_url: Optional[str] = Field(None, max_length=500)

    @field_validator("modality")
    @classmethod
    def _mod(cls, v):
        return _one_of(MODALITIES)(v)

    @field_validator("image_url")
    @classmethod
    def _url(cls, v):
        return _https(v)


class VisitIn(BaseModel):
    kind: str = "clinic"
    reason: Optional[str] = Field(None, max_length=300)
    facility: Optional[str] = Field(None, max_length=120)

    @field_validator("kind")
    @classmethod
    def _kind(cls, v):
        return _one_of(KINDS)(v)


class CheckOutIn(BaseModel):
    summary: Optional[str] = Field(None, max_length=3000)


def _when(v: Optional[datetime]) -> datetime:
    v = v or _now()
    return v if v.tzinfo else v.replace(tzinfo=timezone.utc)



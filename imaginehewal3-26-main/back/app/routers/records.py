@patient_router.get("/primary-care")
def primary_care(db: Session = Depends(get_db), user: User = Depends(get_current_active_user)):
    from app.models.care_plan import DoctorAppointment
    from app.models.user import UserProfile
    p = db.query(UserProfile).filter(UserProfile.user_id == user.id).first()
    doc = db.query(Doctor).filter(Doctor.doctor_id == p.doctor_id).first() if p and p.doctor_id else None
    if not doc:
        return {"doctor": None, "next_appointment": None, "pending_requests": 0, "last_visit": None}
    now = _now()
    appts = db.query(DoctorAppointment).filter(DoctorAppointment.patient_id == user.id, DoctorAppointment.doctor_pk == doc.id,
                                               DoctorAppointment.status.in_(("requested", "confirmed")), DoctorAppointment.starts_at >= now).order_by(DoctorAppointment.starts_at).all()
    nxt = next((a for a in appts if a.status == "confirmed"), None)
    last = db.query(CareVisit).filter(CareVisit.user_id == user.id, CareVisit.doctor_pk == doc.id, CareVisit.checked_out_at.isnot(None)).order_by(CareVisit.checked_out_at.desc()).first()
    return {"doctor": {"id": doc.id, "doctor_id": doc.doctor_id, "name": doc.full_name, "specialization": doc.specialization, "hospital": doc.hospital,
                       "photo_url": doc.profile_image_url, "working_hours": doc.working_hours},
            "next_appointment": {"id": nxt.id, "starts_at": _iso(nxt.starts_at), "mode": nxt.mode, "reason": nxt.reason} if nxt else None,
            "pending_requests": sum(1 for a in appts if a.status == "requested"),
            "last_visit": _visit(last, doc.full_name) if last else None}
